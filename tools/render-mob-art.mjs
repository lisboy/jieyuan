const hex2rgb = (hex) => {
  const n = String(hex).replace('#', '');
  return [parseInt(n.slice(0, 2), 16), parseInt(n.slice(2, 4), 16), parseInt(n.slice(4, 6), 16)];
};
const rgba = (hex, a) => { const [r, g, b] = hex2rgb(hex); return `rgba(${r},${g},${b},${a})`; };
const mix = (a, b, k) => {
  const A = hex2rgb(a), B = hex2rgb(b);
  return '#' + A.map((v, i) => Math.round(v + (B[i] - v) * k).toString(16).padStart(2, '0')).join('');
};

// —— 零件 DSL（逻辑舞台 1000x1000，脚底 ~940，头顶 ≥120）——
//   { t:'p', d }   填充路径
//   { t:'e', x, y, rx, ry, rot? }  椭圆（可旋转）
//   { t:'g', pts } 多边形 "x,y x,y ..."
//   { t:'s', d, w } 描边线（须/藤/腿/尾）
// 层：back（身后零件，先画、用更深的墨色）；base（身体本体）；
//     lo/hi（暗部/亮部，裁剪进身体）；mark（纹样，裁剪进身体）
//     mark 的 mk: el=元气色(默认) | lite=月白 | dark=浓墨 | verdant=苔绿；mo 控制不透明度
const P = (d, o = {}) => ({ t: 'p', d, ...o });
const E = (x, y, rx, ry, o = {}) => ({ t: 'e', x, y, rx, ry, ...o });
const G = (pts, o = {}) => ({ t: 'g', pts, ...o });
const S = (d, w, o = {}) => ({ t: 's', d, w, ...o });

// —— 眼睛的四种画法 ——
// slit：妖兽竖瞳（默认）；round：圆瞳亮珠（幼兽/小动物）；void：影灵无眼白，两点幽光；dot：纯光点（虫/贝/蛛）
function eyesSVG(shape, el) {
  const kind = shape.eyeKind || 'slit';
  return (shape.eyes || []).map(([x, y, r]) => {
    if (kind === 'void') return `
      <ellipse cx="${x}" cy="${y}" rx="${r * 2.6}" ry="${r * 2.2}" fill="${rgba(el, 0.30)}" filter="url(#glow)"/>
      <ellipse cx="${x}" cy="${y}" rx="${r * 0.9}" ry="${r * 1.25}" fill="${rgba(el, 0.95)}" filter="url(#glow)"/>
      <circle cx="${x}" cy="${y}" r="${r * 0.38}" fill="#fffdf6"/>`;
    if (kind === 'dot') return `
      <circle cx="${x}" cy="${y}" r="${r * 2.2}" fill="${rgba(el, 0.35)}" filter="url(#glow)"/>
      <circle cx="${x}" cy="${y}" r="${r * 0.85}" fill="${rgba(mix(el, '#ffffff', 0.65), 1)}"/>`;
    // 眼白不用纯白：掺入元气色，读作"夜里发光的宝珠眼"而不是卡通突眼
    const sclera = rgba(mix(el, '#fff6e2', kind === 'round' ? 0.35 : 0.62), 0.96);
    const pw = kind === 'round' ? 0.5 : 0.42, ph = kind === 'round' ? 0.66 : 1.0;
    return `
      <ellipse cx="${x}" cy="${y}" rx="${r * 3.1}" ry="${r * 2.7}" fill="${rgba(el, 0.36)}" filter="url(#glow)"/>
      <ellipse cx="${x}" cy="${y}" rx="${r * 1.14}" ry="${r * 1.05}" fill="${sclera}"/>
      <ellipse cx="${x}" cy="${y}" rx="${r * pw}" ry="${r * ph}" fill="#140a12"/>
      <circle cx="${x - r * 0.32}" cy="${y - r * 0.36}" r="${r * 0.2}" fill="#ffffff" opacity="0.95"/>`;
  }).join('');
}

