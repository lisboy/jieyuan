/**
 * 分层上色：底色 -> 暗部 -> 亮部 -> 纹样，全部裁剪在身体轮廓里。
 * 再叠两笔全局光：左上一团顶光、脚下一层沉影，让所有妖怪共享同一种"夜里的月光"。
 */
function partSvg(part, pass, el) {
  const attr = (fill, extra = '') => {
    if (part.t === 'e') return `<ellipse cx="${part.x}" cy="${part.y}" rx="${part.rx}" ry="${part.ry}"${part.rot ? ` transform="rotate(${part.rot} ${part.x} ${part.y})"` : ''} fill="${fill}"${extra}/>`;
    if (part.t === 'g') return `<polygon points="${part.pts}" fill="${fill}"${extra}/>`;
    if (part.t === 's') return `<path d="${part.d}" fill="none" stroke="${fill}" stroke-width="${part.w}" stroke-linecap="round"${extra}/>`;
    return `<path d="${part.d}" fill="${fill}"${extra}/>`;
  };
  if (pass === 'back') return attr('url(#backGrad)');
  if (pass === 'base') {
    // 腿/须这类细零件用底色渐变会融进背景：tint 让它带一点元气色，dim 压远感
    if (part.t === 's' && part.tint) return attr(rgba(mix(el, '#14101c', 0.30), part.dim ? 0.6 : 0.95));
    return attr(part.lightStroke ? 'url(#backGrad)' : 'url(#bodyGrad)');
  }
  if (pass === 'lo') return part.lo ? attr(rgba('#050309', part.mo || 0.4), ' filter="url(#blur6)"') : '';
  if (pass === 'hi') return part.hi ? attr(rgba(mix(el, '#fff3dd', 0.62), part.mo == null ? 0.2 : part.mo * 0.26), ' filter="url(#blur8)"') : '';
  if (pass === 'mark') {
    if (!part.mark && !part.mk) return '';
    const base = part.mk === 'lite' ? '#f3ecd8' : part.mk === 'dark' ? '#08060c' : part.mk === 'verdant' ? '#6fa878' : el;
    return attr(rgba(base, part.mo == null ? 0.55 : part.mo));
  }
  return '';
}

function creature(mob, shape, el) {
  const parts = shape.parts || [];
  const back = parts.filter((p) => p.back).map((p) => partSvg(p, 'back', el)).join('');
  const base = parts.filter((p) => !p.back).map((p) => partSvg(p, 'base', el)).join('');
  const clipParts = parts.filter((p) => !p.back && p.t !== 's').map((p) => partSvg(p, 'base', el)).join('');
  const lo = parts.map((p) => partSvg(p, 'lo', el)).join('');
  const hi = parts.map((p) => partSvg(p, 'hi', el)).join('');
  const mark = parts.map((p) => partSvg(p, 'mark', el)).join('');
  const propsBack = (shape.props || []).filter((p) => p.k === 'moon' || p.k === 'shadow').map((p) => prop(p, el)).join('');
  const propsFront = (shape.props || []).filter((p) => p.k !== 'moon' && p.k !== 'shadow').map((p) => prop(p, el)).join('');

  return `
    ${propsBack}
    <!-- 元气晕 -->
    <ellipse cx="500" cy="560" rx="360" ry="400" fill="${rgba(el, 0.10)}" filter="url(#soft)"/>
    <!-- 身后零件 -->
    <g>${back}</g>
    <!-- 身体 -->
    <g>${base}</g>
    <defs><clipPath id="bodyClip">${clipParts}</clipPath></defs>
    <g clip-path="url(#bodyClip)">${lo}</g>
    <g clip-path="url(#bodyClip)">${hi}</g>
    <!-- 全局体积光：左上顶光 + 底部沉影 -->
    <g clip-path="url(#bodyClip)">
      <ellipse cx="420" cy="300" rx="330" ry="250" fill="rgba(255,246,224,0.07)" filter="url(#blur8)"/>
      <ellipse cx="510" cy="905" rx="400" ry="190" fill="rgba(0,0,0,0.30)" filter="url(#blur8)"/>
    </g>
    <g clip-path="url(#bodyClip)">${mark}</g>
    ${eyesSVG(shape, el)}
    ${propsFront}
  `;
}

function scene(mob, kindKey) {
  const el = elements.list[mob.element]?.color || '#cfd8e8';
  const K = KIND[kindKey];
  const shape = shapeFor(mob);
  const bgDeep = mix('#0a0a10', el, 0.10);
  const bgUp = mix('#16151f', el, 0.20);

  const motes = Array.from({ length: 22 }, (_, i) => {
    const s = Math.sin(i * 12.9898) * 43758.5453;
    const rx = ((s - Math.floor(s)) * 900 + 50) | 0;
    const ry = (((s * 7.13) - Math.floor(s * 7.13)) * 800 + 90) | 0;
    const r = 1.2 + ((i % 5) * 1.1);
    return `<circle cx="${rx}" cy="${ry}" r="${r.toFixed(1)}" fill="${rgba(el, 0.14 + (i % 4) * 0.07)}" filter="url(#glow)"/>`;
  }).join('');

  const ground = shape.ground === 'none' ? '' : shape.ground === 'low' ? `
    <ellipse cx="500" cy="944" rx="200" ry="22" fill="rgba(0,0,0,0.30)" filter="url(#blur8)"/>` : `
    <ellipse cx="500" cy="942" rx="240" ry="26" fill="rgba(0,0,0,0.42)" filter="url(#blur8)"/>`;

  const s = ((mob.boss ? K.zoom * 0.82 : K.zoom) * K.h) / 1000;

  return `<!doctype html><html><head><meta charset="utf-8"><style>
  html,body{margin:0;padding:0;background:#06060a;overflow:hidden}
  svg{display:block}
  </style></head><body>
  <svg width="${K.w}" height="${K.h}" viewBox="0 0 ${K.w} ${K.h}" preserveAspectRatio="xMidYMid slice" xmlns="http://www.w3.org/2000/svg">
    <defs>
      <radialGradient id="bg" cx="50%" cy="40%" r="80%">
        <stop offset="0%" stop-color="${bgUp}"/><stop offset="58%" stop-color="${bgDeep}"/><stop offset="100%" stop-color="#07070c"/>
      </radialGradient>
      <linearGradient id="bodyGrad" gradientUnits="userSpaceOnUse" x1="0" y1="160" x2="0" y2="940">
        <stop offset="0%" stop-color="${mix('#2e2836', el, 0.46)}"/>
        <stop offset="46%" stop-color="${mix('#1a1622', el, 0.18)}"/>
        <stop offset="100%" stop-color="#131017"/>
      </linearGradient>
      <linearGradient id="backGrad" gradientUnits="userSpaceOnUse" x1="0" y1="160" x2="0" y2="940">
        <stop offset="0%" stop-color="${mix('#262030', el, 0.34)}"/>
        <stop offset="100%" stop-color="#141019"/>
      </linearGradient>
      <filter id="soft" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="26"/></filter>
      <filter id="glow" x="-120%" y="-120%" width="340%" height="340%"><feGaussianBlur stdDeviation="8"/></filter>
      <filter id="blur6" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="5"/></filter>
      <filter id="blur8" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="11"/></filter>
      <filter id="grain"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="3" stitchTiles="stitch"/>
        <feColorMatrix type="saturate" values="0"/></filter>
      <radialGradient id="vig" cx="50%" cy="50%" r="72%">
        <stop offset="55%" stop-color="rgba(0,0,0,0)"/><stop offset="100%" stop-color="rgba(0,0,0,0.72)"/>
      </radialGradient>
    </defs>

    <rect width="${K.w}" height="${K.h}" fill="url(#bg)"/>
    <!-- 月轮：给深色身体衬一层可读的亮底 -->
    <circle cx="500" cy="380" r="330" fill="${rgba(el, 0.05)}" filter="url(#soft)"/>
    <circle cx="500" cy="380" r="235" fill="${rgba(mix(el, '#ffffff', 0.55), 0.085)}" filter="url(#soft)"/>
    <!-- 远山两叠 -->
    <g filter="url(#soft)" opacity="0.42">
      <path d="M -80 640 C 160 480 330 570 480 480 C 650 380 800 530 1120 440 L 1120 1200 L -80 1200 Z" fill="${rgba(el, 0.14)}"/>
      <path d="M -60 760 C 220 660 420 740 620 660 C 820 580 980 700 1140 640 L 1140 1200 L -60 1200 Z" fill="${rgba('#000000', 0.45)}"/>
    </g>

    <g transform="translate(${K.w / 2},${K.h / 2}) scale(${s}) translate(${-K.cx},${-K.cy})">
      ${ground}
      ${creature(mob, shape, el)}
      ${motes}
      <!-- 脚边雾 -->
      <ellipse cx="500" cy="930" rx="330" ry="36" fill="${rgba(el, 0.10)}" filter="url(#soft)"/>
      <ellipse cx="380" cy="916" rx="190" ry="22" fill="rgba(255,255,255,0.05)" filter="url(#soft)"/>
    </g>

    <rect width="${K.w}" height="${K.h}" fill="url(#vig)"/>
    <rect width="${K.w}" height="${K.h}" filter="url(#grain)" opacity="0.05"/>
  </svg></body></html>`;
}

let shotSeq = 0;
function shoot(htmlFile, png, w, h) {
  execFileSync(CHROME, [
    '--headless=new', '--disable-gpu', '--hide-scrollbars', '--no-first-run',
    '--force-device-scale-factor=1',
    `--user-data-dir=${path.join(process.env.TEMP || process.env.TMP || ROOT, 'shiyuan-chrome-shot-' + process.pid + '-' + (++shotSeq) + '-' + Date.now().toString(36))}`,
    `--window-size=${w},${h}`,
    '--virtual-time-budget=4000',
    `--screenshot=${png}`, htmlUrl(htmlFile)
  ], { stdio: ['ignore', 'ignore', 'pipe'] });
}
const htmlUrl = (p) => 'file:///' + p.replace(/\\/g, '/').replace(/ /g, '%20');

if (!NO_SHOT && !CHROME) { console.error('未找到 Chrome，无法截图。'); process.exit(1); }
const tmp = path.join(ROOT, 'target', 'mob-art');
fs.mkdirSync(tmp, { recursive: true });

let made = 0;
let skippedBoss = 0;
for (const mob of mobsDoc.mobs) {
  if (FILTER && !mob.id.includes(FILTER)) continue;
  // 妖王已有真出图（tools/boss-art.py），这个渲染器不许覆盖；要看效果加 --force-boss
  if (mob.boss && !FORCE_BOSS) { skippedBoss++; continue; }
  const dir = path.join(ROOT, 'content', 'art', `${mob.name}-${mob.id}`);
  fs.mkdirSync(dir, { recursive: true });
  for (const [key, K] of Object.entries(KIND)) {
    if (ONLY_KIND && ONLY_KIND !== key) continue;
    const htmlFile = path.join(tmp, `${mob.id}-${key}.html`);
    fs.writeFileSync(htmlFile, scene(mob, key), 'utf8');
    if (NO_SHOT) continue;
    const png = path.join(dir, `${K.stem}.png`);
    try {
      const t0 = Date.now();
      shoot(htmlFile, png, K.w, K.h);
      const kb = fs.existsSync(png) ? (fs.statSync(png).size / 1024) | 0 : 0;
      console.log(`  ✓ ${mob.id}/${key} -> ${mob.name}-${mob.id}/${K.stem}.png (${kb}KB, ${Date.now() - t0}ms)`);
      made++;
    } catch (e) {
      console.log(`  ! ${mob.id}/${key} 失败：${String(e.message).split('\n')[0]}`);
    }
  }
}
console.log(`小怪立绘：输出 ${made} 张` + (skippedBoss ? `（妖王 ${skippedBoss} 只已有真出图，已跳过；要覆盖加 --force-boss）` : ''));
