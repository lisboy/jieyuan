def build_prompt(mob, el, kind):
    d = DESIGN[mob["id"]]
    fac = mob["faction"]
    main_hex, main_label = el["color"], el["label"]
    aux_hex, aux_label = d["aux"]
    look = mob.get("look") or {}
    head = [
        PREFIX,
        LAW,
        COMPOSE[kind].format(pose=POSE[mob["id"]][0 if kind == "standee" else 1], set=d.get("scene") or SCENE[fac]),
        f"角色：{mob['name']}「{mob.get('title', '')}」，关卡小怪（杂兵，不是可抽取角色），六气属{main_label}",
        f"配色：主色 {main_hex}（{main_label}）用于躯体最大色块；辅色 {aux_label} {aux_hex} 用于腹甲、羽缘、布片、缠绳、器物等第二大面积，必须与主色形成看得出的搭配；中性色只用米白与墨石；鎏金只出现在一两件小配饰",
        f"【小怪识别——三项照原样画】体型骨架：{d['body']}；妖相细部：{d['parts']}；标志器物：{d['tool']}",
        f"妖气所在：{d['wisp']}",
    ]
    if d.get("teen"):
        head.append(GUARD_TEEN_OBJECT)
    else:
        head.append("不得误导：这不是可抽取的角色，不画人形美貌，不画成装束精致的人；也不许可爱化成宠物或吉祥物")
    if kind == "scene":
        head.insert(0, "【本张为空景，以下抠图/怪物纪律仅用于统一画风与配色，画面里不出现任何生物】")
    head += [
        f"场景线索（只取气质与光，不画环境）：{look.get('set', '')}",
        f"动作与画面重点：只画它本身的那一瞬（{look.get('motif', '')}），不加任何技能特效、光斑、粒子与漂浮物——那些由运行时叠在抠图之上",
        f"气质线索：{d['aura']}",
        "一致性：同一副骨架、同一套主辅配色、同一件标志器物；不同资产只改姿态、机位与光的方向，不许换形、不许改配色、不许把角/尾/羽/腕改掉",
        SUFFIX,
    ]
    return "\n".join(head)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--groups", type=int, default=0)
    ap.add_argument("--check", action="store_true", help="只核对设计表覆盖与姿态表覆盖")
    n = ap.parse_args()
    doc = json.load(open(os.path.join(ROOT, "content", "mobs.json"), encoding="utf-8"))
    els = json.load(open(os.path.join(ROOT, "content", "elements.json"), encoding="utf-8"))["list"]
    mobs = [m for m in doc["mobs"] if not m.get("boss")]
    only = {s for s in n.only.split(",") if s}

    missing = [m["id"] for m in mobs if (not only or m["id"] in only) and m["id"] not in DESIGN]
    missing_pose = [m["id"] for m in mobs if (not only or m["id"] in only) and m["id"] not in POSE]
    if missing or missing_pose:
        print(f"设计表缺：{missing}\n姿态表缺：{missing_pose}")
        raise SystemExit(1)
    if n.check:
        print(f"OK {len(mobs)} 只小怪，设计/姿态齐全")
        return

    os.makedirs(OUT, exist_ok=True)
    os.makedirs(RAWM, exist_ok=True)
    rows = []
    for mob in mobs:
        if only and mob["id"] not in only:
            continue
        el = els[mob["element"]]
        for kind in ("standee", "dynamic", "scene"):
            text = build_prompt(mob, el, kind)
            p = os.path.join(OUT, f"mob-prompt-{mob['id']}-{kind}.txt")
            with open(p, "w", encoding="utf-8") as f:
                f.write(text + "\n")
        rows.append((mob["id"], mob["name"], mob["faction"]))
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as f:
        f.write("# 小怪出图清单\n\n每只三张：standee 1024x1536 灰底 / dynamic 1024x1536 灰底 / scene 2048x1152 空景。\n"
                "原图落 `.raw-mobs/<id>/<kind>.png`，不要自己抠、不要跑 build/validate/--mark。\n\n")
        for i, (mid, name, fac) in enumerate(rows):
            f.write(f"- {name} `{mid}` [{fac}] → .raw-mobs/{mid}/{{standee,dynamic,scene}}.png\n")

    if n.groups:
        # 按势力连续切组，每组尽量同势力（画面基调一致，便于同一子代理内自校）
        per = (len(rows) + n.groups - 1) // n.groups
        for g in range(n.groups):
            chunk = rows[g * per:(g + 1) * per]
            if not chunk:
                continue
            with open(os.path.join(OUT, f"group-{g + 1}.txt"), "w", encoding="utf-8") as f:
                for mid, name, fac in chunk:
                    f.write(f"{name}\t{mid}\t{fac}\n")
            print(f"group-{g + 1}: " + "、".join(x[1] for x in chunk))
    print(f"写了 {len(rows)} 只小怪 × 3 份 prompt → {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
