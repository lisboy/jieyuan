def build_prompt(boss, mob, kind):
    b = BOSS[boss]
    main_hex, main_label = b["main"]
    aux_hex, aux_label = b["aux"]
    look = mob.get("look") or {}
    lines = [
        PREFIX,
        LAW,
        COMPOSE[kind].format(pose=POSE[boss][kind]),
        f"角色：{mob['name']}「{mob.get('title', '')}」，妖王，六气属{main_label}",
        f"配色：主色 {main_hex}（{main_label}）用于躯体与服装最大色块；辅色 {aux_label} {aux_hex} 用于内衬、披风内侧、束带、器物缠绳等第二大面积，必须与主色形成看得出的搭配；中性色只用米白与墨石；鎏金只出现在一两件小配饰",
        f"【妖王识别——三项照原样画】体型骨架：{b['body']}；标志性器物：{b['extra']}；妖相细部：{b['anchors']}",
        f"场景线索（只取气质，不画环境）：{look.get('set', '')}",
        f"动作与画面重点：只画妖王本身的那一瞬（{look.get('motif', '')}），不加任何技能特效、光斑、粒子与漂浮物——那些由运行时叠在抠图之上",
        f"气质线索：{b['aura']}",
        "一致性：同一副骨架、同一套主辅配色、同一件标志器物；不同资产只改姿态、机位与光的方向，不许换形、不许改配色、不许把角/尾/鳞改掉",
        "不得性感化：妖王不画魅态、不画裸露、不做撩人姿态；威压来自体量、器物与光影，不来自身体",
        SUFFIX,
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    n = ap.parse_args()
    doc = json.load(open(os.path.join(ROOT, "content", "mobs.json"), encoding="utf-8"))
    only = {s for s in n.only.split(",") if s}
    os.makedirs(OUT, exist_ok=True)
    made = 0
    for mob in doc["mobs"]:
        if not mob.get("boss") or (only and mob["id"] not in only):
            continue
        for kind in ("standee", "dynamic"):
            text = build_prompt(mob["id"], mob, kind)
            p = os.path.join(OUT, f"boss-prompt-{mob['id']}-{kind}.txt")
            with open(p, "w", encoding="utf-8") as f:
                f.write(text + "\n")
            made += 1
            print(f"{mob['id']:<14}{kind:<9}{len(text):>5} 字 -> {os.path.relpath(p, ROOT)}")
    print(f"共 {made} 份 prompt")


if __name__ == "__main__":
    main()
